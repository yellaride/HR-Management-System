export async function sendBirthdayEmail(
  email: string,
  name: string,
  designation?: string,
  department?: string
): Promise<boolean> {
  // Accepted for caller compatibility (cron route passes them) but not yet
  // rendered in the email template. The void reads are intentional no-ops.
  void designation;
  void department;

  if (!isResendConfigured()) {
    console.error("Resend API Key (RESEND_API_KEY) is missing. Birthday email dispatch skipped.");
    return false;
  }

  try {
    const htmlContent = getBirthdayEmailTemplate(name);

    const emailResponse = await resend.emails.send({
      from: getResendFromAddress(),
      to: [email],
      subject: `Happy Birthday, ${name}! 🎂 - VibeFlow Workspace`,
      html: htmlContent,
    });

    if (emailResponse.error) {
      console.error(`Resend birthday delivery failed for ${name}:`, emailResponse.error);
      return false;
    }

    return true;
  } catch (error) {
    console.error(`An unexpected error occurred during birthday email delivery to ${name}:`, error);
    return false;
  }
}